/**
 * Generate a Tabular CSV Risk Register
 */
export function generateCsvReport(nodes: EcosystemNode[]): string {
  const headers = [
    'Package Name',
    'Version',
    'Category',
    'Systemic Score',
    'Conventional CVSS',
    'Severity',
    'Critical Chokepoint',
    'Transitive Dependents (Repos)',
    'Critical Services Reached',
    'Centrality Velocity (%)',
    'Maintainers Count',
    'Weekly Downloads',
    'Operational Domain'
  ];

  const rows = nodes.map(node => [
    `"${node.name}"`,
    `"${node.version}"`,
    `"${node.category}"`,
    node.systemicScore,
    node.conventionalScore,
    `"${node.conventionalSeverity}"`,
    node.articulationPoint ? 'TRUE' : 'FALSE',
    node.dependents,
    node.tier1Reach,
    node.centralityVelocity ? `+${node.centralityVelocity}%` : '0%',
    node.maintainers,
    `"${node.weeklyDownloads}"`,
    `"${node.operationalDomain || 'General OSS'}"`
  ]);

  return [headers.join(','), ...rows.map(r => r.join(','))].join('\n');
}

/**
 * Helper to download content as a file via native browser Blob
 */
export function downloadFile(content: string, filename: string, mimeType: string): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(url);
}
